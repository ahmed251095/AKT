def terms(arch):
    """Every translatable term of a view arch, in document order."""
    found = []

    def grab(term):
        found.append(term)
        return term
    xml_translate(grab, arch)
    return found


def page_arch(url, path, lang):
    """Rebuild a page's arch the same way build_module.py does."""
    inner = forms.rewrite(url, htmlslice.inner(common.body(path, lang)))
    return '<div id="wrap" class="oe_structure">%s</div>' % inner


def layout_arch(lang):
    """The layout as the module actually ships it.

    The nav bar and the language switch are QWeb in the generated layout -
    the bar is read from website.menu so the client can edit it - so their
    text is not in the view and must not be collected here either. It would
    otherwise claim terms the footer needs: "Careers" is الوظائف in the bar
    and فرص العمل in the footer, and whichever was collected first would win
    in both places.
    """
    f = dict(common.pages(lang))['/']
    header = common.body(f, lang, common.HEADER)
    nav = htmlslice.slice_element(header, re.compile(r'<nav[^>]*id="primary-nav"'))
    switch = htmlslice.slice_element(header, re.compile(r'<a class="language-switch"'))
    header = header.replace(nav, '').replace(switch, '')
    return '<div>%s%s%s</div>' % (header,
                                  common.body(f, lang, common.FOOTER),
                                  common.body(f, lang, common.FLOAT))


