def quote(text):
    """A msgid/msgstr body, split over lines the way gettext does."""
    text = (text.replace('\\', '\\\\').replace('"', '\\"')
                .replace('\t', '\\t'))
    lines = text.split('\n')
    if len(lines) == 1:
        return '"%s"' % lines[0]
    out = ['""']
    for i, line in enumerate(lines):
        out.append('"%s%s"' % (line, '\\n' if i < len(lines) - 1 else ''))
    return '\n'.join(out)


def main():
    out = [HEADER]
    for msgid in sorted(CODE):
        out.append('#. module: akt_website\n')
        out.append('#: code:addons/akt_website/controllers/main.py:0\n')
        out.append('msgid %s\n' % quote(msgid))
        out.append('msgstr %s\n\n' % quote(CODE[msgid]))

    path = os.path.join(common.MOD, 'i18n/ar.po')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(''.join(out))
    print('wrote %s with %d terms' % (path, len(CODE)))


if __name__ == '__main__':
    main()
